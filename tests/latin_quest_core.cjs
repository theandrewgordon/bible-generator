const assert=require('node:assert/strict');
const {matches,buildQueue,record,lookupStudy,isStudyQuestion}=require('../static/js/latin-quest-core.js');
const meaning={id:'noun-001:meaning',card:'noun-001',mode:'meaning',details:'Noun.',answers:['servant','slave'],latin:false};
assert(matches(meaning,'a servant'));assert(matches(meaning,'slave'));assert(!matches(meaning,'window'));assert(!matches(meaning,'slav'));
assert(matches({...meaning,details:'Verb.',answers:['fight']},'to fight'));
assert(matches({...meaning,details:'Verb.',answers:["don't know",'do not know']},"I don't know"));
assert(matches({...meaning,answers:['faith','trust']},'it means trust'));
assert(matches({...meaning,mode:'reverse',answers:['rēx'],latin:true},'rex'));
const attrs={...meaning,id:'grammar-noun-011:grammar',mode:'grammar',answers:['Declension, gender, number, and case.']};
assert(matches(attrs,'case gender declension number'));assert(!matches(attrs,'case gender'));
const qs=Array.from({length:20},(_,i)=>({...meaning,id:`noun-${i}:meaning`,card:`noun-${i}`}));
const prior={[qs[0].id]:{attempts:2,correct:0,streak:0},[qs[1].id]:{attempts:1,correct:1,streak:1}};
assert.equal(buildQueue(qs,'meaning',10,prior).length,10);assert.equal(new Set(buildQueue(qs,'meaning',5,prior).map(q=>q.card)).size,5);
assert.deepEqual(buildQueue(qs,'meaning',10,prior,true).map(q=>q.id),[qs[0].id]);
assert.equal(record(prior,qs[0],true,true)[qs[0].id].streak,0);assert.equal(record(prior,qs[0],true,false)[qs[0].id].streak,1);
assert.equal(buildQueue([...qs,qs[0]],'meaning',30,{}).length,20);
assert.equal(buildQueue(qs,'meaning',50,{}).length,20);
